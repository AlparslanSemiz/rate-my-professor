package com.pse;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.sql.Timestamp;
import java.time.LocalDateTime;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;

@SpringBootTest(properties = {
		"spring.datasource.url=jdbc:h2:mem:token-service-test;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1",
		"spring.datasource.driver-class-name=org.h2.Driver",
		"spring.datasource.username=sa",
		"spring.datasource.password=",
		"spring.sql.init.mode=never"
})
class TokenServiceIntegrationTests {

	@Autowired
	private TokenService tokenService;

	@Autowired
	private JdbcTemplate jdbcTemplate;

	@BeforeEach
	void createMockTables() {
		jdbcTemplate.execute("DROP TABLE IF EXISTS magic_login_tokens");
		jdbcTemplate.execute("""
				CREATE TABLE magic_login_tokens (
					id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					email VARCHAR(255) NOT NULL,
					token TEXT NOT NULL,
					expires_at TIMESTAMP NOT NULL,
					used BOOLEAN NOT NULL DEFAULT FALSE
				)
				""");
	}

	@Test
	void createAndSaveTokenPersistsUsableToken() {
		String email = "student@kit.edu";

		String token = tokenService.createAndSaveToken(email);

		assertNotNull(token);
		assertEquals(1, countTokens(email, token, false));
		assertTrue(tokenService.verifyToken(email, token));
		assertTrue(isTokenUsed(email, token));
		assertFalse(tokenService.verifyToken(email, token));
	}

	@Test
	void verifyTokenRejectsExpiredToken() {
		String email = "expired@kit.edu";
		String token = "expired-token";
		insertToken(email, token, LocalDateTime.now().minusDays(1), false);

		assertFalse(tokenService.verifyToken(email, token));
		assertFalse(isTokenUsed(email, token));
	}

	@Test
	void verifyTokenRejectsWrongEmailOrToken() {
		String email = "student@kit.edu";
		String token = "valid-token";
		insertToken(email, token, LocalDateTime.now().plusMinutes(5), false);

		assertFalse(tokenService.verifyToken("other@kit.edu", token));
		assertFalse(tokenService.verifyToken(email, "wrong-token"));
		assertFalse(isTokenUsed(email, token));
	}

	private void insertToken(String email, String token, LocalDateTime expiresAt, boolean used) {
		jdbcTemplate.update("""
				INSERT INTO magic_login_tokens(email, token, expires_at, used)
				VALUES (?, ?, ?, ?)
				""",
				email,
				token,
				Timestamp.valueOf(expiresAt),
				used);
	}

	private int countTokens(String email, String token, boolean used) {
		Integer count = jdbcTemplate.queryForObject("""
				SELECT COUNT(*)
				FROM magic_login_tokens
				WHERE email = ?
				  AND token = ?
				  AND used = ?
				""",
				Integer.class,
				email,
				token,
				used);

		return count == null ? 0 : count;
	}

	private boolean isTokenUsed(String email, String token) {
		Boolean used = jdbcTemplate.queryForObject("""
				SELECT used
				FROM magic_login_tokens
				WHERE email = ?
				  AND token = ?
				""",
				Boolean.class,
				email,
				token);

		return Boolean.TRUE.equals(used);
	}
}
